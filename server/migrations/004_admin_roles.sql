-- Роли в админ-панели: не все сотрудники должны иметь доступ к самым рискованным
-- действиям (удалённое выполнение команд). Три уровня, от простого к полному:
--   operator      — оповещения, просмотр дашборда, ничего разрушительного
--   administrator — полный доступ, включая команды на кассах
--   superadmin    — то же, что administrator, плюс управление самими учётками панели
--                   (экран управления учётками ещё не построен — колонка заведена заранее)
ALTER TABLE admin_users ADD COLUMN role TEXT NOT NULL DEFAULT 'administrator'
    CHECK (role IN ('operator', 'administrator', 'superadmin'));
