-- Папки назначения для раскатки файлов: при раскатке администратор выбирает «куда» из
-- понятного списка («Рабочий стол всех пользователей»), а не вспоминает каждый раз
-- полный путь. Хранится только папка — имя файла подставляется при раскатке (по
-- умолчанию — имя загруженного файла). Список дополняется на странице «Файлы».
-- Обратные слэши в строках SQLite — обычные символы, экранировать не нужно.
CREATE TABLE deploy_destinations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    path TEXT NOT NULL,
    description TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

