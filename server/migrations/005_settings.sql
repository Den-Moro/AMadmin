-- Настройки по умолчанию (см. AGENTS.md, "Интерфейс настроек") — простая таблица
-- ключ-значение, не отдельная подсистема: осознанно просто, чтобы не усложнять
-- архитектуру ради шести полей. Значения всегда текстовые (число/булево — тоже строкой,
-- '1'/'0' для булевых) — так проще редактировать через один общий UI без спец-полей под
-- каждый тип.
CREATE TABLE settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

INSERT INTO settings (key, value) VALUES
    -- Strict — неважные оповещения тоже принудительные (topmost); Soft — немодальные,
    -- в углу экрана. См. AGENTS.md, ForceMode.
    ('force_mode_default', 'soft'),
    -- Догон пропущенных важных оповещений при следующем выходе ПК на связь. 1 = вкл.
    ('catchup_missed_default', '1'),
    -- Сколько секунд кнопка закрытия окна оповещения неактивна (виден обратный отсчёт).
    ('close_delay_seconds', '30'),
    -- Размер окна оповещения по умолчанию: small / medium / large.
    ('window_size_default', 'medium'),
    -- Название обслуживающей IT-компании — показывается в окне оповещения у кассира.
    ('brand_name', ''),
    -- Контакт для связи (телефон/почта) — показывается там же.
    ('brand_contact', '');
