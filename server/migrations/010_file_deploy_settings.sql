-- Настройки раскатки файлов — приходят агенту вместе с каждой командой file_deploy
-- (см. CommandsController::index), поэтому меняются из панели без перезапуска касс.
INSERT INTO settings (key, value) VALUES
    -- Асинхронная загрузка: файл качается в фоне, а агент тем временем выполняет
