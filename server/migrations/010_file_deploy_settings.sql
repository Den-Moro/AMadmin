    ('file_deploy_async', '1'),

    -- Сколько файлов одна касса может качать одновременно (в асинхронном режиме).
    ('file_deploy_max_parallel', '2'),

    -- Потолок скорости скачивания на одну кассу, КБ/с. 0 — без ограничения. Значение
    -- download_limit_kbps в config.json кассы, если оно не 0, имеет приоритет — так
    -- отдельному магазину с узким каналом можно поставить свой лимит.
    ('file_deploy_limit_kbps', '0');
