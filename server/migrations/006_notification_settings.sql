-- Тонкие настройки показа оповещений. Всё, что раньше было захардкожено в клиенте
-- (время до разблокировки кнопки, подтверждение закрытия, защита от случайного касания),
-- теперь настраивается из панели — чтобы менять поведение на кассах без пересборки агента.
INSERT INTO settings (key, value) VALUES
    -- Отдельное время до разблокировки кнопки для ВАЖНЫХ оповещений: их обычно нужно
    -- читать внимательнее, чем обычные. 0 = использовать общее значение.
    ('close_delay_seconds_important', '30'),

    -- Закрытие в два шага: первое нажатие просит подтвердить. Защита от случайного
    -- касания на сенсорных кассах, где кассир постоянно тыкает в экран.
    ('confirm_close_required', '1'),

    -- Сколько миллисекунд после разблокировки кнопки игнорировать нажатия. Ловит тап,
    -- который прилетел ровно в момент разблокировки.
    ('accidental_tap_guard_ms', '600'),

    -- Звуковой сигнал при важном оповещении — чтобы заметили в шумном зале.
    ('sound_on_important', '1'),

    -- Сколько окон подряд показывать за один опрос. Остальные подождут следующего —
    -- иначе кассир получит десять окон подряд и просто закликает их.
    ('max_windows_per_poll', '3'),

    -- Угол экрана для мягких (неважных) оповещений.
    ('soft_corner', 'bottom-right'),

    -- Тихие часы: в это время неважные оповещения не показываются (ждут окончания).
    -- На важные не действует никогда — так требует ТЗ.
    ('quiet_hours_enabled', '0'),
    ('quiet_hours_from', '22:00'),
    ('quiet_hours_to', '08:00');
